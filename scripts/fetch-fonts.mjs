// Fetches Google Fonts (Oswald + Space Grotesk) as local woff2 files with a
// generated @font-face stylesheet — removes the Google Fonts runtime dependency.
// Usage: node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT_DIR = fileURLToPath(new URL("../public/fonts/", import.meta.url));
const CSS_OUT = fileURLToPath(new URL("../src/styles/fonts.css", import.meta.url));

// Modern UA → woff2 + unicode-range subsets.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0 Safari/537.36";
const API =
  "https://fonts.googleapis.com/css2?family=Oswald:wght@400;500;700&family=Space+Grotesk:wght@400;500;700&display=swap";

const res = await fetch(API, { headers: { "User-Agent": UA } });
if (!res.ok) {
  console.error(`Google Fonts CSS request failed: HTTP ${res.status}`);
  process.exit(1);
}
const css = await res.text();

const faces = [];
const seen = new Map();
const faceRegex = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/g;
let match;
while ((match = faceRegex.exec(css))) {
  const subset = match[1];
  const block = match[2];
  const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
  const weight = /font-weight:\s*(\d+)/.exec(block)?.[1];
  const url = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
  if (!family || !weight || !url) continue;
  // Keep latin + latin-ext only.
  if (!/^latin/.test(subset)) continue;
  const slug = `${family.toLowerCase().replace(/\s+/g, "-")}-${weight}-${subset}.woff2`;
  faces.push({ family, weight, slug, range: range?.trim() });
  seen.set(slug, url);
}

await mkdir(OUT_DIR, { recursive: true });
let cssOut = "/* Self-hosted fonts — generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n";
for (const [slug, url] of seen) {
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  await writeFile(join(OUT_DIR, slug), buf);
  console.log(`ok    fonts/${slug} (${(buf.length / 1024).toFixed(0)} KB)`);
}
for (const face of faces) {
  cssOut += `@font-face {
  font-family: '${face.family}';
  font-style: normal;
  font-weight: ${face.weight};
  font-display: swap;
  src: url('/fonts/${face.slug}') format('woff2');
${face.range ? `  unicode-range: ${face.range};\n` : ""}}\n`;
}
await writeFile(CSS_OUT, cssOut);
console.log(`ok    src/styles/fonts.css (${faces.length} faces)`);
